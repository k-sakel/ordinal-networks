"""Write ``paper/numbers.tex``: every measured number quoted in the manuscript, as a
LaTeX macro, taken from ``paper/results/*.json`` (written by ``make_figures.py`` and
``benchmarks/compare.py``). Run after those:

    python paper/make_numbers.py
"""
import json
import math
from pathlib import Path

from constants import H_HENON, LN2

HERE = Path(__file__).parent
RES = HERE / "results"


def load(name):
    with open(RES / f"{name}.json") as f:
        return json.load(f)


def sig(v, n=2):
    """v rounded to n significant digits, without exponent notation."""
    if v == 0:
        return "0"
    d = n - 1 - math.floor(math.log10(abs(v)))
    return f"{round(v, d):.{max(d, 0)}f}"


def sci(v):
    """LaTeX for a small number, e.g. 3 x 10^{-16}."""
    if v == 0:
        return "0"
    mant, e = f"{v:.0e}".split("e")          # rounds first, so 9.7e-16 -> 1e-15, not 10e-16
    return rf"${mant}\times10^{{{int(e)}}}$"


def power(n):
    e = round(math.log10(n))
    return rf"10^{{{e}}}" if 10 ** e == n else f"{n:,}".replace(",", r"\,")


def main():
    m = {}
    b = load("benchmark")
    mach = b["machine"]
    m["nCores"] = str(mach["cpu_count"])
    m["machine"] = mach["platform"].replace("_", r"\_")
    m["pyVersion"] = mach["python"]
    m["ordpyVersion"] = str(mach["ordpy"])
    vs_n = b["vs_n"]
    both = [r for r in vs_n if "ordpy" in r]
    last = both[-1]
    m["nOrdpyMax"] = power(last["n"])
    m["speedupN"] = sig(last["ordpy"] / last["ordinal_networks"], 2)
    m["tOnEight"] = sig(vs_n[-1]["ordinal_networks"], 2)
    vs_m = b["vs_m"]
    m["tMmax"] = sig(vs_m[-1]["ordinal_networks"], 2)
    bm = [r for r in vs_m if "ordpy" in r]
    m["tOrdpyMthree"] = sig(bm[0]["ordpy"], 2)
    m["tOrdpyMlast"] = sig(bm[-1]["ordpy"], 2)
    m["mOrdpyLast"] = str(bm[-1]["m"])
    for mm, key in ((6, "scaleSix"), (16, "scaleSixteen")):
        rows = sorted((r for r in b["threads"] if r["m"] == mm), key=lambda r: r["threads"])
        m[key] = sig(rows[0]["ordinal_networks"] / rows[-1]["ordinal_networks"], 2)

    e = load("entropy_logistic")
    ms = e["m"]
    i12 = ms.index(12)
    ilast = len(ms) - 2                      # the last m has no m+1 partner for Method III
    m["mEntropy"] = str(ms[ilast])
    m["errTPE"] = sig(100 * (e["TPE"][ilast] / LN2 - 1), 2)
    m["errG"] = sig(100 * (e["lnG"][ilast] / LN2 - 1), 2)
    m["errRho"] = sig(100 * abs(e["ln_rho"][i12] / LN2 - 1), 1)
    m["tSweepLog"] = sig(e["seconds_symbolise_sweep"], 2)
    m["tQuick"] = sig(load("quickstart")["seconds"], 2)

    a = load("agreement_ordpy")
    m["maxDiffH"] = sci(a["max_abs_diff_H"])
    m["maxDiffC"] = sci(a["max_abs_diff_C"])

    s = load("scale_henon")
    run = s["runs"][-1]
    m["scaleExp"] = str(round(math.log10(run["n"])))
    m["scaleMmax"] = str(run["m"][-1])
    m["scaleRho"] = f"{run['ln_rho'][-1]:.4f}"
    m["scaleSeconds"] = sig(run["seconds_sweep"], 2)
    m["scaleEigMinutes"] = sig(run["seconds_eig"] / 60, 2)
    m["scaleNodes"] = sig(run["V"][-1] / 1e6, 2)
    prev = s["runs"][-2]
    agree = [mm for mm, u, v in zip(run["m"], prev["ln_rho"], run["ln_rho"]) if abs(u / v - 1) < 0.01]
    k = 0
    while k < len(agree) and agree[k] == run["m"][0] + k:
        k += 1
    if k == 0:
        raise SystemExit("scale_henon.json: the two longest series already differ by more than 1 % at the "
                         "smallest m, so the sentence quoting \\scaleAgreeM no longer holds; revise the text")
    m["scaleAgreeM"] = str(agree[k - 1])              # largest m up to which the two longest series agree within 1 %
    m["scaleRhoPrev"] = f"{prev['ln_rho'][-1]:.4f}"
    short = s["runs"][0]
    below = [mm for mm, v in zip(short["m"], short["ln_rho"]) if mm > 8 and v < H_HENON]
    if not below:
        raise SystemExit(f"scale_henon.json: the shortest series (N = {short['n']}) never falls below the "
                         f"reference {H_HENON}, so the sentence quoting \\scaleShortCross no longer holds; "
                         f"revise the text")
    m["scaleShortCross"] = str(below[0])
    m["scaleShortLast"] = f"{short['ln_rho'][-1]:.2f}"

    c = load("collapse_logistic")
    m["collapseN"] = f"{c['n_collapse']:,}".replace(",", r"\,")
    m["collapsePEbefore"] = f"{c['pe_rate'][0]:.3f}"
    m["collapsePEafter"] = f"{c['pe_rate'][-1]:.3f}"
    m["collapseRho"] = f"{c['ln_rho'][-1]:.3f}"
    e10 = math.floor(math.log10(c["n"][-1]))
    m["collapseNmax"] = rf"{c['n'][-1] / 10 ** e10:g}\times10^{{{e10}}}"

    lines = ["% Generated by paper/make_numbers.py from paper/results/*.json. Do not edit."]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in m.items()]
    (HERE / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for k, v in m.items():
        print(f"{k:14s} {v}")


if __name__ == "__main__":
    main()
